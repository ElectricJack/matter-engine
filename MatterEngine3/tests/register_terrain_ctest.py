#!/usr/bin/env python3
"""Register the generated-memory terrain slice from existing native executables.

Build the eight Make targets listed in MAKE_TESTS, then run:
  python3 MatterEngine3/tests/register_terrain_ctest.py --test-dir /tmp/terrain-ctest
  ctest --test-dir /tmp/terrain-ctest --output-on-failure -j4

Optionally configure/build libs/TerrainGeneration separately with
MATTER_TERRAIN_BUILD_EXAMPLES=OFF and pass --standalone-dir BUILD_DIR.
Only its memory fixtures are registered; package reload and dependency audits
read files and are deliberately excluded. This harness does not qualify the
whole engine, collision sessions, demand-cache tests, or filesystem behavior.
"""

import argparse
from pathlib import Path


MAKE_TESTS = (
    "terrain_field_tests",
    "terrain_mesher_tests",
    "seam_weld_tests",
    "contour_seam_tests",
    "contour_mesh_tests",
    "contour_engine_tests",
    "terrain_collision_definition_tests",
    "terrain_collision_artifact_tests",
)


def quote(value):
    """CMake bracket arguments preserve spaces, semicolons and backslashes."""
    value = str(value)
    delimiter = "="
    while "]" + delimiter + "]" in value:
        delimiter += "="
    return "[" + delimiter + "[" + value + "]" + delimiter + "]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--test-dir", required=True, type=Path)
    parser.add_argument("--build-dir", type=Path,
                        default=Path(__file__).resolve().parent / "build")
    parser.add_argument("--standalone-dir", type=Path)
    args = parser.parse_args()
    cases = [(name, args.build_dir / name, (), ()) for name in MAKE_TESTS]
    if args.standalone_dir:
        root = args.standalone_dir
        cases += [
            ("terrain.region_inputs.v1", root / "matter_terrain_region_tests", (), ()),
            ("terrain.mesh_products.v1", root / "matter_terrain_meshing_tests", (),
             ("MATTER_CONTOUR_SEAMS=1",)),
            ("terrain.mesh_rollback_rejected.v1", root / "matter_terrain_meshing_tests",
             ("rollback",), ("MATTER_CONTOUR_SEAMS=0",)),
            ("terrain.mesh_native_parity.v1", root / "matter_terrain_native_parity_tests",
             (), ("MATTER_CONTOUR_SEAMS=1",)),
            ("terrain.legacy_surface_noise", root / "matter_terrain_legacy_surface_tests",
             (), ()),
        ]
        cases += [
            ("terrain.example.coordinator_" + fixture + ".v1",
             root / "matter_terrain_coordinator_integration_tests", (fixture,),
             ("MATTER_CONTOUR_SEAMS=1",))
            for fixture in ("adjacent", "late_completion", "resolution_change", "faults")
        ]
    resolved = []
    for name, executable, arguments, environment in cases:
        executable = executable.resolve()
        if not executable.is_file() and executable.with_suffix(".exe").is_file():
            executable = executable.with_suffix(".exe")
        if not executable.is_file():
            parser.error("build the existing target first: " + str(executable))
        resolved.append((name, executable, arguments, environment))
    destination = args.test_dir.resolve()
    destination.mkdir(parents=True, exist_ok=True)
    working = destination / "empty-runtime-cwd"
    working.mkdir(exist_ok=True)
    lines = ["# Generated by register_terrain_ctest.py; this is a focused slice."]
    for name, executable, arguments, environment in resolved:
        command = " ".join(quote(item) for item in (name, executable, *arguments))
        lines.append("add_test(" + command + ")")
        properties = ("WORKING_DIRECTORY " + quote(working) +
                      " TIMEOUT 180 LABELS " + quote("terrain;memory-fixture"))
        properties += " ENVIRONMENT " + quote(";".join(
            environment or ("MATTER_CONTOUR_SEAMS=0",)))
        lines.append("set_tests_properties(" + quote(name) +
                     " PROPERTIES " + properties + ")")
    (destination / "CTestTestfile.cmake").write_text("\n".join(lines) + "\n")
    print("Registered", len(resolved), "focused tests in", destination)


if __name__ == "__main__":
    main()
