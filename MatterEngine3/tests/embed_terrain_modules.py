#!/usr/bin/env python3
"""Embed actual terrain JS inputs at build time for file-free test execution."""
import argparse
import json
from pathlib import Path


def emit_source(lines, name, data):
    # Bounded literals also compile with MSVC. Explicit lengths retain all bytes.
    lines += [f"inline std::string {name}() {{", "    std::string source;",
              f"    source.reserve({len(data)});"]
    for start in range(0, len(data), 1024):
        chunk = data[start:start + 1024]
        encoded = "".join(f"\\x{byte:02x}" for byte in chunk)
        lines.append(f'    source.append("{encoded}", {len(chunk)});')
    lines += ["    return source;", "}"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = args.repo_root.resolve()
    lines = ["// Generated by embed_terrain_modules.py; do not edit.",
             "#pragma once", '#include "module_resolver.h"',
             "#include <string>", "#include <vector>",
             "namespace terrain_test_modules {"]
    inputs = {
        "world_sector": "projects/world_demo/objects/templates/WorldSector.js",
        "mountain_world": "projects/world_demo/scenes/streaming/StreamMountain/StreamMountain.js",
        "mountain_sector": "projects/world_demo/scenes/streaming/StreamMountain/objects/WorldSector.js",
    }
    for name, relative in inputs.items():
        emit_source(lines, name, (root / relative).read_bytes())

    # Project-over-engine precedence matches production. Embed the available
    # library bytes; the real resolver still selects/folds only imported modules.
    modules = {}
    for tier in ("projects/world_demo/shared-lib", "MatterEngine3/shared-lib"):
        for path in sorted((root / tier).glob("*.js")):
            modules.setdefault("shared-lib/" + path.stem, path)
    for index, (_, path) in enumerate(sorted(modules.items())):
        emit_source(lines, f"module_{index}", path.read_bytes())
    lines += ["inline std::vector<module_resolver::ResolvedModule> modules() {",
              "    return {"]
    for index, (specifier, path) in enumerate(sorted(modules.items())):
        identity = path.relative_to(root).as_posix()
        lines.append(f"        {{{json.dumps(specifier)}, module_{index}(), {json.dumps(identity)}}},")
    lines += ["    };", "}", "} // namespace terrain_test_modules", ""]
    content = "\n".join(lines).encode("utf-8")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_bytes() != content:
        args.output.write_bytes(content)


if __name__ == "__main__":
    main()
